// Asset URLs carry a content hash so edge and browser caches never serve a stale file after a deploy.
const assetUrl = async (path) => {
  const hash = createHash("sha256").update(await readFile(join(root, "public", path))).digest("hex").slice(0, 10);
  return `/${path}?v=${hash}`;
};
// The hero signal map adapts to any number of services, so its per-node motion is generated, not hand-written.
{
  const n = JSON.parse(await readFile(join(root, "src/content/en.json"), "utf8")).services.items.length;
  const step = 10 / n;
  let css = "/* Generated by src/build.mjs. Do not edit. */\n";
  for (let i = 0; i < n; i++) {
    const a = ((-90 + (360 / n) * i) * Math.PI) / 180;
    const x = (210 * Math.cos(a)).toFixed(1), y = (210 * Math.sin(a)).toFixed(1);
    css += `.d${i} { --x: ${x}px; --y: ${y}px; animation-delay: ${(i * step + 1).toFixed(2)}s; }\n`;
    css += `.n${i} .sig-flash { animation-delay: ${((i * step + 2.6) % 10).toFixed(2)}s; }\n`;
  }
  await mkdir(join(root, "public/assets/css"), { recursive: true });
  await writeFile(join(root, "public/assets/css/signal.css"), css);
}
